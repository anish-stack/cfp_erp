#!/usr/bin/env bash
# Writes /etc/nginx/conf.d/cloudflare-realip.conf so $remote_addr = the real visitor IP (not Cloudflare's).
# Safe to re-run (cron monthly). Falls back to the built-in list if cloudflare.com is unreachable.
set -euo pipefail
OUT=/etc/nginx/conf.d/cloudflare-realip.conf
FALLBACK_V4="173.245.48.0/20 103.21.244.0/22 103.22.200.0/22 103.31.4.0/22 141.101.64.0/18 108.162.192.0/18 190.93.240.0/20 188.114.96.0/20 197.234.240.0/22 198.41.128.0/17 162.158.0.0/15 104.16.0.0/13 104.24.0.0/14 172.64.0.0/13 131.0.72.0/22"
FALLBACK_V6="2400:cb00::/32 2606:4700::/32 2803:f800::/32 2405:b500::/32 2405:8100::/32 2a06:98c0::/29 2c0f:f248::/32"
V4=$(curl -fsS --max-time 10 https://www.cloudflare.com/ips-v4 || echo "$FALLBACK_V4")
V6=$(curl -fsS --max-time 10 https://www.cloudflare.com/ips-v6 || echo "$FALLBACK_V6")
{
  echo "# generated by cloudflare-realip.sh $(date -I)"
  for ip in $V4 $V6; do echo "set_real_ip_from $ip;"; done
  echo "real_ip_header CF-Connecting-IP;"
} > "$OUT"
echo "Wrote $OUT"
